--creacion de la base de datos
CREATE DATABASE control_gastos_personales;
--creacion de las tablas
CREATE TABLE categorias (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nombre VARCHAR(80) NOT NULL,
                            descripcion VARCHAR(255),

                            CONSTRAINT uq_categoria_nombre
                                UNIQUE (nombre),

                            CONSTRAINT ck_categoria_nombre
                                CHECK (length(trim(nombre)) > 0)
);

CREATE TABLE gastos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        descripcion VARCHAR(160) NOT NULL,
                        monto NUMERIC(12, 2) NOT NULL,
                        fecha DATE NOT NULL,
                        estado VARCHAR(12) NOT NULL,
                        categoria_id BIGINT NOT NULL,

                        CONSTRAINT ck_gasto_descripcion
                            CHECK (length(trim(descripcion)) > 0),

                        CONSTRAINT ck_gasto_monto
                            CHECK (monto > 0),

                        CONSTRAINT ck_gasto_estado
                            CHECK (estado IN ('PAGADO', 'PENDIENTE')),

                        CONSTRAINT fk_gasto_categoria
                            FOREIGN KEY (categoria_id)
                                REFERENCES categorias(id)
);

--creacion de los indices para filtrar
CREATE INDEX idx_gastos_fecha
    ON gastos(fecha);

CREATE INDEX idx_gastos_categoria
    ON gastos(categoria_id);

CREATE INDEX idx_gastos_estado
    ON gastos(estado);


